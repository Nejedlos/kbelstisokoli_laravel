        class RingBuffer {
            constructor(maxSize) {
                this.maxSize = maxSize;
                this.buffer = [];
            }
            push(item) {
                this.buffer.push(item);
                if (this.buffer.length > this.maxSize) {
                    this.buffer.shift();
                }
            }
            toArray() {
                return [...this.buffer];
            }
            get length() {
                return this.buffer.length;
            }
        }

